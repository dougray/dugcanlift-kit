"""Tests for Tools/build_branded_foods.py, against a hand-written sample.

`fdc-branded-sample/` holds four CSVs in USDA's own column layout, written by
hand -- twenty-two records including discontinued, missing-macro, bad
check digit, all-zeros and UPC-A/EAN-13 duplicates -- and `expected.json`,
what the builder must make of them, also written by hand. Neither is ever
generated by the builder: a fixture written by the code under test proves only
that the code agrees with itself.

`data/barcodes.json` is the barcode fixture every LIFT build reads codes
against (copied from lift-ios, where it was written by hand from GS1's and
Wikipedia's examples). The builder must read every code in it the same way.

Run: python3 -I Tools/tests/test_build_branded_foods.py
"""
import gzip
import hashlib
import importlib.util
import json
import shutil
import sqlite3
import sys
import tempfile
import unittest
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SAMPLE = HERE / "fdc-branded-sample"
EXPECTED = json.loads((SAMPLE / "expected.json").read_text(encoding="utf-8"))
CSVS = ("nutrient.csv", "food.csv", "branded_food.csv", "food_nutrient.csv")

# -I keeps the script's own directory off sys.path, so load the builder by path.
_spec = importlib.util.spec_from_file_location("build_branded_foods", ROOT / "Tools/build_branded_foods.py")
bbf = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(bbf)

COLUMNS = ("code", "name", "brand", "kcal", "protein", "carbs", "fat",
           "fiber", "sugar", "satfat", "sodium", "serving", "ml")


class Built:
    """One build of the sample, shared by the tests that only read it."""
    tmp = None
    manifest = None

    @classmethod
    def get(cls):
        if cls.manifest is None:
            cls.tmp = tempfile.mkdtemp(prefix="branded-foods-test-")
            cls.manifest = bbf.build(SAMPLE, Path(cls.tmp) / "out", released="2026-04-30")
        return cls.manifest, Path(cls.tmp) / "out"


def connect(path):
    db = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    return db


def lookup(db, code):
    return db.execute(
        "SELECT p.code, p.name, b.name, p.kcal, p.protein, p.carbs, p.fat, p.fiber, p.sugar, "
        "p.satfat, p.sodium, p.serving, p.ml FROM products p LEFT JOIN brands b ON b.id = p.brand "
        "WHERE p.code = ?", (code,)).fetchone()


class ReadingABarcode(unittest.TestCase):
    """The builder reads codes as the apps do, against the shared fixture."""

    fixture = json.loads((ROOT / "data/barcodes.json").read_text(encoding="utf-8"))

    def test_the_fixture_is_the_pinned_copy(self):
        digest = hashlib.sha256((ROOT / "data/barcodes.json").read_bytes()).hexdigest()
        self.assertEqual(digest, (ROOT / "data/barcodes.sha256").read_text().strip(),
                         "data/barcodes.json does not match data/barcodes.sha256")

    def test_every_valid_code_normalises_as_the_fixture_says(self):
        for case in self.fixture["valid"]:
            with self.subTest(case["raw"]):
                self.assertEqual(bbf.read_code(case["raw"]), (case["normalised"], None))

    def test_every_upce_expansion_normalises_as_the_fixture_says(self):
        # The builder never sees a symbology, so it reads the UPC-A expansion.
        for case in self.fixture["upce"]:
            with self.subTest(case["raw"]):
                self.assertEqual(bbf.expand_upce(case["raw"]), case["expandsTo"])
                self.assertEqual(bbf.read_code(case["expandsTo"]), (case["normalised"], None))

    def test_every_invalid_code_is_refused(self):
        for case in self.fixture["invalid"]:
            with self.subTest(case["raw"]):
                code, problem = bbf.read_code(case["raw"])
                self.assertIsNone(code)
                self.assertIsNotNone(problem)

    def test_all_zeros_is_refused_by_rule_though_its_arithmetic_passes(self):
        self.assertTrue(bbf.check_digit_ok("0000000000000"))
        self.assertEqual(bbf.read_code("0000000000000"), (None, "zeros"))
        self.assertEqual(bbf.read_code("000000000000"), (None, "zeros"))

    def test_upc_a_ean_13_and_gtin_14_spellings_meet(self):
        spellings = {bbf.read_code(c)[0] for c in ("036000291452", "0036000291452", "00036000291452")}
        self.assertEqual(spellings, {"36000291452"})

    def test_nine_to_eleven_digits_are_gtins_whose_zeros_were_dropped(self):
        self.assertEqual(bbf.read_code("36000291452"), ("36000291452", None))
        self.assertEqual(bbf.read_code("36000291453"), (None, "check"))
        self.assertEqual(bbf.read_code("1234565"), (None, "length"))

    def test_eight_digits_are_ean_8_only(self):
        # 06543226 is a valid UPC-E (the fixture says so) but not a valid EAN-8.
        self.assertEqual(bbf.read_code("06543226"), (None, "check"))
        self.assertEqual(bbf.read_code("73513537"), ("73513537", None))

    def test_why_not(self):
        self.assertEqual(bbf.read_code(""), (None, "none"))
        self.assertEqual(bbf.read_code(None), (None, "none"))
        self.assertEqual(bbf.read_code("12345678901A"), (None, "malformed"))
        self.assertEqual(bbf.read_code("123456789012345"), (None, "length"))


class ReadingValues(unittest.TestCase):
    def test_tenths_round_half_up(self):
        for text, want in (("3.45", 35), ("15.25", 153), ("0.04", 0), ("0.05", 1), ("2", 20),
                           ("11.3", 113), ("4.17", 42), ("0", 0)):
            with self.subTest(text):
                self.assertEqual(bbf.tenths(text), want)

    def test_unknown_is_never_zero(self):
        for text in ("", " ", None, "-0.5", "abc", "NaN", "Infinity"):
            with self.subTest(text):
                self.assertIsNone(bbf.tenths(text))

    def test_dates(self):
        self.assertEqual(bbf.iso_date("2024-01-10"), "2024-01-10")
        self.assertEqual(bbf.iso_date("4/1/2019"), "2019-04-01")
        self.assertEqual(bbf.iso_date("soon"), "")
        self.assertEqual(bbf.iso_date(""), "")


class TheSampleBuild(unittest.TestCase):
    def setUp(self):
        self.manifest, self.out = Built.get()
        self.db = connect(self.out / self.manifest["db"]["file"])

    def tearDown(self):
        self.db.close()

    def test_exactly_the_expected_products_and_values(self):
        got = [dict(zip(COLUMNS, row)) for row in self.db.execute(
            "SELECT p.code, p.name, b.name, p.kcal, p.protein, p.carbs, p.fat, p.fiber, p.sugar, "
            "p.satfat, p.sodium, p.serving, p.ml FROM products p LEFT JOIN brands b ON b.id = p.brand "
            "ORDER BY p.code")]
        want = [{k: p[k] for k in COLUMNS} for p in EXPECTED["products"]]
        self.assertEqual(got, want)

    def test_every_drop_is_counted_for_its_reason(self):
        self.assertEqual(self.manifest["counts"], EXPECTED["counts"])
        self.assertEqual(self.manifest["products"], len(EXPECTED["products"]))

    def test_dropped_codes_match_nothing(self):
        for code in (5901234123457, 70000000010, 70000000041, 36000291453, 0, 6543226):
            with self.subTest(code):
                self.assertIsNone(lookup(self.db, code))

    def test_one_row_answers_every_spelling_of_a_code(self):
        for raw in ("036000291452", "0036000291452", "00036000291452"):
            code, _ = bbf.read_code(raw)
            self.assertEqual(lookup(self.db, int(code))[1], "DIET COLA")

    def test_brands_are_one_table_with_no_repeats(self):
        names = [n for (n,) in self.db.execute("SELECT name FROM brands ORDER BY id")]
        self.assertEqual(names, EXPECTED["brands"])
        self.assertEqual(self.manifest["brands"], len(EXPECTED["brands"]))

    def test_meta_says_where_the_numbers_came_from(self):
        meta = dict(self.db.execute("SELECT key, value FROM meta"))
        self.assertEqual(meta, {
            "format": "1",
            "source": "USDA FoodData Central, Branded Foods",
            "license": "CC0 1.0 Universal (public domain)",
            "released": "2026-04-30",
            "release": "branded-foods-2026-04.1",
            "products": "9",
        })

    def test_the_file_identifies_itself(self):
        self.assertEqual(self.db.execute("PRAGMA application_id").fetchone()[0], 0x4C494654)
        self.assertEqual(self.db.execute("PRAGMA user_version").fetchone()[0], 1)

    def test_the_barcode_is_the_rowid_and_nothing_else_is_indexed(self):
        indexes = self.db.execute(
            "SELECT name FROM sqlite_master WHERE type = 'index' AND tbl_name IN ('products', 'brands')"
        ).fetchall()
        self.assertEqual(indexes, [])
        rows = self.db.execute("SELECT rowid, code FROM products").fetchall()
        self.assertTrue(all(rowid == code for rowid, code in rows))

    def test_search_is_contentless_and_detail_none(self):
        sql = self.db.execute("SELECT sql FROM sqlite_master WHERE name = 'search'").fetchone()[0]
        self.assertIn("content=''", sql)
        self.assertIn("detail=none", sql)
        # Contentless: the index holds no copy of the text to give back.
        self.assertEqual(self.db.execute("SELECT text FROM search LIMIT 1").fetchone(), (None,))

    def search(self, query):
        return sorted(c for (c,) in self.db.execute(
            "SELECT rowid FROM search WHERE search MATCH ?", (query,)))

    def test_search_finds_names_brands_prefixes_and_ignores_accents(self):
        self.assertEqual(self.search("cola"), [36000291452, 10036000291459])
        self.assertEqual(self.search("fizzco"), [36000291452, 10036000291459])
        self.assertEqual(self.search("gran*"), [9780306406157])
        self.assertEqual(self.search("creme brulee"), [4006381333931])
        self.assertEqual(self.search("hearth mix"), [70000000027])

    def test_search_never_finds_a_dropped_product(self):
        for query in ("crackers", "mystery", "chips", "chocolate", "soup", "bread", "gum", "tea"):
            with self.subTest(query):
                self.assertEqual(self.search(query), [])

    def test_search_has_no_relevance_to_offer(self):
        # detail=none stores no term frequencies, so bm25 is 0 for every hit:
        # the apps order results themselves. Pinned so nobody relies on rank.
        scores = {s for (s,) in self.db.execute("SELECT bm25(search) FROM search WHERE search MATCH 'cola'")}
        self.assertEqual(scores, {0.0})

    def test_the_manifest_hashes_what_was_written(self):
        db = self.out / self.manifest["db"]["file"]
        gz = self.out / self.manifest["gz"]["file"]
        self.assertEqual(hashlib.sha256(db.read_bytes()).hexdigest(), self.manifest["db"]["sha256"])
        self.assertEqual(hashlib.sha256(gz.read_bytes()).hexdigest(), self.manifest["gz"]["sha256"])
        self.assertEqual(db.stat().st_size, self.manifest["db"]["bytes"])
        self.assertEqual(gzip.decompress(gz.read_bytes()), db.read_bytes())
        on_disk = json.loads((self.out / "branded-foods.json").read_text(encoding="utf-8"))
        self.assertEqual(on_disk, self.manifest)

    def test_the_manifest_names_the_release_asset(self):
        self.assertEqual(self.manifest["release"], "branded-foods-2026-04.1")
        self.assertEqual(self.manifest["gz"]["file"], "branded-foods-2026-04.1.db.gz")
        self.assertEqual(self.manifest["url"],
                         "https://github.com/dougray/dugcanlift-kit/releases/download/"
                         "branded-foods-2026-04.1/branded-foods-2026-04.1.db.gz")
        self.assertEqual(sorted(self.manifest["input"]["files"]), sorted(CSVS))


class Reproducible(unittest.TestCase):
    def test_two_builds_are_byte_identical(self):
        first, out1 = Built.get()
        with tempfile.TemporaryDirectory() as tmp:
            second = bbf.build(SAMPLE, Path(tmp), released="2026-04-30")
            self.assertEqual(second["db"]["sha256"], first["db"]["sha256"])
            self.assertEqual(second["gz"]["sha256"], first["gz"]["sha256"])
            self.assertEqual(second["rowsSha256"], first["rowsSha256"])

    def test_the_zip_reads_as_the_directory_does_and_names_its_release(self):
        first, _ = Built.get()
        with tempfile.TemporaryDirectory() as tmp:
            zpath = Path(tmp) / "FoodData_Central_branded_food_csv_2026-04-30.zip"
            with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
                for name in CSVS:
                    z.write(SAMPLE / name, f"FoodData_Central_branded_food_csv_2026-04-30/{name}")
            m = bbf.build(zpath, Path(tmp) / "out")
            self.assertEqual(m["released"], "2026-04-30")
            self.assertEqual(m["db"]["sha256"], first["db"]["sha256"])
            self.assertEqual(m["input"]["name"], zpath.name)
            self.assertEqual(m["input"]["sha256"], hashlib.sha256(zpath.read_bytes()).hexdigest())

    def test_a_rebuild_of_one_release_gets_its_own_name(self):
        with tempfile.TemporaryDirectory() as tmp:
            m = bbf.build(SAMPLE, Path(tmp), released="2026-04-30", build_number=2)
            self.assertEqual(m["release"], "branded-foods-2026-04.2")
            self.assertTrue((Path(tmp) / "branded-foods-2026-04.2.db.gz").exists())


class RefusingInputItWasNotWrittenFor(unittest.TestCase):
    def copy_sample(self, tmp):
        d = Path(tmp) / "sample"
        shutil.copytree(SAMPLE, d)
        return d

    def test_a_renumbered_nutrient_stops_the_build(self):
        with tempfile.TemporaryDirectory() as tmp:
            d = self.copy_sample(tmp)
            text = (d / "nutrient.csv").read_text(encoding="utf-8")
            (d / "nutrient.csv").write_text(text.replace('"Total lipid (fat)"', '"Sugars, added"'),
                                            encoding="utf-8")
            with self.assertRaisesRegex(bbf.BuildError, "1004"):
                bbf.build(d, Path(tmp) / "out", released="2026-04-30")

    def test_a_renamed_nutrient_stops_the_build_and_says_which(self):
        # USDA renamed 2000 between releases ("Sugars, total including NLEA" to
        # "Total Sugars"); a rename is read by a person before it is accepted.
        with tempfile.TemporaryDirectory() as tmp:
            d = self.copy_sample(tmp)
            text = (d / "nutrient.csv").read_text(encoding="utf-8")
            (d / "nutrient.csv").write_text(
                text.replace('"Total Sugars"', '"Sugars, total including NLEA"'), encoding="utf-8")
            with self.assertRaisesRegex(bbf.BuildError, r"nutrient 2000 .*Sugars, total including NLEA"):
                bbf.build(d, Path(tmp) / "out", released="2026-04-30")

    def test_a_missing_column_stops_the_build(self):
        with tempfile.TemporaryDirectory() as tmp:
            d = self.copy_sample(tmp)
            text = (d / "branded_food.csv").read_text(encoding="utf-8")
            (d / "branded_food.csv").write_text(text.replace('"gtin_upc"', '"gtin"', 1), encoding="utf-8")
            with self.assertRaisesRegex(bbf.BuildError, "gtin_upc"):
                bbf.build(d, Path(tmp) / "out", released="2026-04-30")

    def test_no_release_date_stops_the_build(self):
        with tempfile.TemporaryDirectory() as tmp:
            with self.assertRaisesRegex(bbf.BuildError, "release date"):
                bbf.build(SAMPLE, Path(tmp))

    def test_the_command_line_exits_2_on_bad_input(self):
        with tempfile.TemporaryDirectory() as tmp:
            import contextlib, io
            with contextlib.redirect_stderr(io.StringIO()) as err:
                code = bbf.main([str(Path(tmp) / "nothing.zip"), "--released", "2026-04-30", "--out", tmp])
            self.assertEqual(code, 2)
            self.assertIn("no such zip or directory", err.getvalue())


def tearDownModule():
    if Built.tmp:
        shutil.rmtree(Built.tmp, ignore_errors=True)


if __name__ == "__main__":
    unittest.main(verbosity=1)
